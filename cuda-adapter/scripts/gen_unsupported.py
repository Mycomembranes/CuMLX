"""Generate stubs for every CUDA 10.1 Driver API symbol the forwarder does not implement.

Reads the FWD_API markers in shim/cuda_fwd.c and the export list in
symbols/cuda_10_1.txt, and writes shim/generated/cuda_unsupported.c. Each stub
returns CUDA_ERROR_NOT_SUPPORTED (through fwd_unsupported, which also traces).

Every cu* function returns CUresult, and both the x86_64 and arm64 calling
conventions let a callee ignore arguments it does not declare, so `(void)` is a
correct definition for a stub that reads none of them.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
IMPLEMENTED = re.compile(r"^FWD_API\s+CUresult\s+(cu\w+)\s*\(", re.M)


def main() -> int:
    wanted = [line.strip() for line in (ROOT / "symbols/cuda_10_1.txt").read_text().splitlines() if line.strip()]
    implemented = set(IMPLEMENTED.findall((ROOT / "shim/cuda_fwd.c").read_text()))
    extra = sorted(implemented - set(wanted))
    if extra:
        print(f"gen_unsupported: implemented but not in the CUDA 10.1 export list: {extra}", file=sys.stderr)
        return 1
    missing = [name for name in wanted if name not in implemented]
    out = [
        "/*",
        " * SPDX-FileCopyrightText: Copyright (c) 2026 NVIDIA CORPORATION & AFFILIATES. All rights reserved.",
        " * SPDX-License-Identifier: Apache-2.0",
        " *",
        " * GENERATED by scripts/gen_unsupported.py - do not edit.",
        f" * {len(implemented)} of {len(wanted)} CUDA 10.1 Driver API symbols are implemented in cuda_fwd.c;",
        f" * the {len(missing)} below return CUDA_ERROR_NOT_SUPPORTED.",
        " */",
        "",
        "typedef int CUresult;",
        "CUresult fwd_unsupported(const char *name, int *warned);",
        "",
        "#define FWD_STUB(name) \\",
        '    __attribute__((visibility("default"))) CUresult name(void) { \\',
        "        static int warned; \\",
        "        return fwd_unsupported(#name, &warned); \\",
        "    }",
        "",
    ]
    out += [f"FWD_STUB({name})" for name in missing]
    target = ROOT / "shim/generated/cuda_unsupported.c"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(out) + "\n")
    print(f"gen_unsupported: {len(implemented)} implemented, {len(missing)} stubs -> {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
