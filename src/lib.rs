#[derive(Debug)]
pub struct Error(pub String);

impl std::fmt::Display for Error {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(&self.0)
    }
}
impl std::error::Error for Error {}

pub(crate) fn err(s: impl Into<String>) -> Error {
    Error(s.into())
}

pub type Handle = *mut c_void;
type FnCreate = unsafe extern "C" fn(*mut Handle, usize, *const c_char) -> c_int;
type FnDestroy = unsafe extern "C" fn(*mut Handle) -> c_int;
type FnCompile = unsafe extern "C" fn(Handle, c_int, *const *const c_char) -> c_int;
type FnSize = unsafe extern "C" fn(Handle, *mut usize) -> c_int;
type FnGet = unsafe extern "C" fn(Handle, *mut c_void) -> c_int;
type FnVersion = unsafe extern "C" fn(*mut c_uint, *mut c_uint) -> c_int;
type FnNum = unsafe extern "C" fn(*mut c_int) -> c_int;
type FnArchs = unsafe extern "C" fn(*mut c_int) -> c_int;

/// Result-code names from nvPTXCompiler.h.
pub fn result_name(code: c_int) -> &'static str {
    match code {
        0 => "NVPTXCOMPILE_SUCCESS",
        1 => "NVPTXCOMPILE_ERROR_INVALID_COMPILER_HANDLE",
        2 => "NVPTXCOMPILE_ERROR_INVALID_INPUT",
        3 => "NVPTXCOMPILE_ERROR_COMPILATION_FAILURE",
        4 => "NVPTXCOMPILE_ERROR_INTERNAL",
        5 => "NVPTXCOMPILE_ERROR_OUT_OF_MEMORY",
        6 => "NVPTXCOMPILE_ERROR_COMPILER_INVOCATION_INCOMPLETE",
        7 => "NVPTXCOMPILE_ERROR_UNSUPPORTED_PTX_VERSION",
        8 => "NVPTXCOMPILE_ERROR_UNSUPPORTED_DEVSIDE_SYNC",
        9 => "NVPTXCOMPILE_ERROR_CANCELLED",
        _ => "NVPTXCOMPILE_ERROR_<unknown>",
    }
}

