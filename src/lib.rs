#[cfg(all(target_os = "macos", target_arch = "aarch64"))]
mod imp {
    use super::*;
    use binary_ko_loader::inproc::{ar, exec::LoadedImage, glibc_shim, link, x18};

    pub struct NvPtxCompiler {
        _image: LoadedImage,
        create: FnCreate,
        destroy: FnDestroy,
        compile: FnCompile,
        prog_size: FnSize,
        prog: FnGet,
        err_size: FnSize,
        err_log: FnGet,
        info_size: FnSize,
        info_log: FnGet,
        version: FnVersion,
        num_archs: FnNum,
        archs: FnArchs,
        pub report: LoadReport,
        /// Archive/x18-manifest/binary hashes of what was actually linked.
        pub identity: crate::identity::Identity,
    }

    // The loaded compiler is re-entrant per handle (NVIDIA documents the API as
    // thread-safe for distinct handles).
    unsafe impl Send for NvPtxCompiler {}
    unsafe impl Sync for NvPtxCompiler {}

    /// Output of one compilation.
    pub struct Compiled {
        pub cubin: Vec<u8>,
        pub info_log: String,
    }

    impl NvPtxCompiler {
        pub fn load(archive: &Path, manifest: &Path) -> Result<Self, Error> {
            let t0 = std::time::Instant::now();
            let bytes = std::fs::read(archive)
                .map_err(|e| err(format!("read {}: {e}", archive.display())))?;
            let mtext = std::fs::read_to_string(manifest).map_err(|e| {
                err(format!(
                    "read x18 manifest {}: {e} (run portkit/ptxas-native/build.sh)",
                    manifest.display()
                ))
            })?;
            let ident = crate::identity::Identity::from_parts(
                archive,
                Some(crate::identity::sha256_hex(&bytes)),
                manifest,
                Some(crate::identity::sha256_hex(mtext.as_bytes())),
            );
            if !ident.verified()
                && std::env::var_os("PTXAS_NATIVE_ALLOW_UNPINNED").is_none_or(|v| v != "1")
            {
                return Err(err(format!(
                    "{} (set PTXAS_NATIVE_ALLOW_UNPINNED=1 only while regenerating the x18 manifest for a new redist)",
                    ident.problems.join("; ")
                )));
            }
            let rows = x18::parse_manifest(&mtext).map_err(|e| err(e.0))?;
            let members = ar::parse_ar(&bytes).map_err(|e| err(e.0))?;
            let n = members.len();
            let objs = members
                .iter()
                .map(|m| link::ObjectFile::parse(&m.name, m.data))
                .collect::<Result<Vec<_>, _>>()
                .map_err(|e| err(e.0))?;
            let mut plan = link::LinkPlan::plan(objs, rows).map_err(|e| err(e.0))?;
            let image = LoadedImage::load(&mut plan, &glibc_shim::resolve).map_err(|e| err(e.0))?;
            crate::crash::install(image.base() as u64, image.linked.total_size);
            if let Some(path) = std::env::var_os("PTXAS_NATIVE_MAP") {
                // symbolization aid: base + per-section offsets
                let mut s = format!("base {:#x}\n", image.base() as u64);
                for (off, size, m, n) in plan.section_map() {
                    s.push_str(&format!("{off:#010x} {size:#08x} {m} {n}\n"));
                }
                let _ = std::fs::write(path, s);
            }
            unsafe { image.run_ctors() };
            let sym = |name: &str| -> Result<usize, Error> {
                image
                    .symbol(name)
                    .map(|p| p as usize)
                    .ok_or_else(|| err(format!("symbol {name} not found in archive")))
            };
            unsafe {
                Ok(Self {
                    create: std::mem::transmute::<usize, FnCreate>(sym("nvPTXCompilerCreate")?),
                    destroy: std::mem::transmute::<usize, FnDestroy>(sym("nvPTXCompilerDestroy")?),
                    compile: std::mem::transmute::<usize, FnCompile>(sym("nvPTXCompilerCompile")?),
                    prog_size: std::mem::transmute::<usize, FnSize>(sym(
                        "nvPTXCompilerGetCompiledProgramSize",
                    )?),
                    prog: std::mem::transmute::<usize, FnGet>(sym(
                        "nvPTXCompilerGetCompiledProgram",
                    )?),
                    err_size: std::mem::transmute::<usize, FnSize>(sym(
                        "nvPTXCompilerGetErrorLogSize",
                    )?),
                    err_log: std::mem::transmute::<usize, FnGet>(sym("nvPTXCompilerGetErrorLog")?),
                    info_size: std::mem::transmute::<usize, FnSize>(sym(
                        "nvPTXCompilerGetInfoLogSize",
                    )?),
                    info_log: std::mem::transmute::<usize, FnGet>(sym("nvPTXCompilerGetInfoLog")?),
                    version: std::mem::transmute::<usize, FnVersion>(sym(
                        "nvPTXCompilerGetVersion",
                    )?),
                    num_archs: std::mem::transmute::<usize, FnNum>(sym(
                        "nvPTXCompilerGetNumSupportedArchs",
                    )?),
                    archs: std::mem::transmute::<usize, FnArchs>(sym(
                        "nvPTXCompilerGetSupportedArchs",
                    )?),
                    report: LoadReport {
                        members: n,
                        stats: image.linked.stats.clone(),
                        image_bytes: image.linked.total_size,
                        text_bytes: image.linked.text_size,
                        load_ms: t0.elapsed().as_millis(),
                    },
                    identity: ident,
                    _image: image,
                })
            }
        }

        pub fn load_default() -> Result<Self, Error> {
            Self::load(&default_archive(), &default_manifest())
        }

        pub fn version(&self) -> Result<(u32, u32), Error> {
            let (mut a, mut b) = (0u32, 0u32);
            let r = unsafe { (self.version)(&mut a, &mut b) };
            if r != 0 {
                return Err(err(result_name(r)));
            }
            Ok((a, b))
        }

        pub fn supported_archs(&self) -> Result<Vec<i32>, Error> {
            let mut n = 0;
            let r = unsafe { (self.num_archs)(&mut n) };
            if r != 0 {
                return Err(err(result_name(r)));
            }
            let mut v = vec![0i32; n.max(0) as usize];
            let r = unsafe { (self.archs)(v.as_mut_ptr()) };
            if r != 0 {
                return Err(err(result_name(r)));
            }
            Ok(v)
        }

        fn log(&self, h: Handle, size: FnSize, get: FnGet) -> String {
            let mut n = 0usize;
            unsafe {
                if size(h, &mut n) != 0 || n == 0 {
                    return String::new();
                }
                let mut buf = vec![0u8; n + 1];
                if get(h, buf.as_mut_ptr() as *mut c_void) != 0 {
                    return String::new();
                }
                let end = buf.iter().position(|&b| b == 0).unwrap_or(buf.len());
                String::from_utf8_lossy(&buf[..end]).into_owned()
            }
        }

        /// Compile PTX with ptxas-style options (e.g. `--gpu-name=sm_120`, `-O3`).
        pub fn compile(&self, ptx: &[u8], options: &[String]) -> Result<Compiled, Error> {
            let mut h: Handle = std::ptr::null_mut();
            let r = unsafe { (self.create)(&mut h, ptx.len(), ptx.as_ptr() as *const c_char) };
            if r != 0 {
                return Err(err(format!("nvPTXCompilerCreate: {}", result_name(r))));
            }
            let copts: Vec<CString> = options
                .iter()
                .map(|o| CString::new(o.as_str()).unwrap())
                .collect();
            let ptrs: Vec<*const c_char> = copts.iter().map(|c| c.as_ptr()).collect();
            let r = unsafe { (self.compile)(h, ptrs.len() as c_int, ptrs.as_ptr()) };
            let info = self.log(h, self.info_size, self.info_log);
            if r != 0 {
                let elog = self.log(h, self.err_size, self.err_log);
                unsafe { (self.destroy)(&mut h) };
                return Err(err(format!(
                    "nvPTXCompilerCompile: {} ({r})\n{elog}{info}",
                    result_name(r)
                )));
            }
            let mut n = 0usize;
            let r = unsafe { (self.prog_size)(h, &mut n) };
            if r != 0 {
                unsafe { (self.destroy)(&mut h) };
                return Err(err(format!("GetCompiledProgramSize: {}", result_name(r))));
            }
            let mut cubin = vec![0u8; n];
            let r = unsafe { (self.prog)(h, cubin.as_mut_ptr() as *mut c_void) };
            unsafe { (self.destroy)(&mut h) };
            if r != 0 {
                return Err(err(format!("GetCompiledProgram: {}", result_name(r))));
            }
            Ok(Compiled {
                cubin,
                info_log: info,
            })
        }
    }
}

